export const CONTENT_PAGES: ContentPage[] = [...FEATURES, ...GUIDES];

export const FEATURE_PAGES = FEATURES;
export const GUIDE_PAGES = GUIDES;

export function getContentPage(kind: ContentPage["kind"], slug: string): ContentPage | undefined {
  return CONTENT_PAGES.find((p) => p.kind === kind && p.slug === slug);
}

/** "feature/tax-invoice" -> { href, title } สำหรับลิงก์ภายใน */
export function resolveRelated(ref: string): { href: string; title: string } | null {
  const [kind, slug] = ref.split("/");
  const page = CONTENT_PAGES.find((p) => p.kind === kind && p.slug === slug);
  if (!page) return null;
  return { href: kind === "feature" ? `/features/${slug}` : `/guide/${slug}`, title: page.h1 };
}
