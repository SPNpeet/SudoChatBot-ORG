import type { SupabaseClient } from "@supabase/supabase-js";

/** เหตุการณ์ที่ตอบคำถาม "คนเดินไปถึงขั้นไหนแล้วหยุด" */
export type TrackEvent =
  | "report_viewed"     // เปิดหน้ารายงาน+ภาษี
  | "doc_printed"       // เปิดหน้าพิมพ์/PDF ของเอกสาร
  | "share_link_copied"; // คัดลอกลิงก์ส่งให้ลูกค้า (ขั้นก่อนได้เงิน)

export async function track(
  svc: SupabaseClient, shopId: string, userId: string | null,
  event: TrackEvent, details?: Record<string, unknown>,
): Promise<void> {
  try {
    await svc.from("audit_logs").insert({
      shop_id: shopId,
      actor_type: "user",
      actor_id: userId,
      action: event,
      resource_type: "usage",
      resource_id: null,
      details: details ?? {},
    });
  } catch {
    // เงียบโดยตั้งใจ — บันทึกไม่ได้ต้องไม่ทำให้ผู้ใช้เปิดรายงาน/พิมพ์เอกสารไม่ได้
  }
}
