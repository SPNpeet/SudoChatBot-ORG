// ---------- embedding (ใช้ตรรกะเดียวกับ src/lib/tax-kb.ts) ----------
const DIMS = 1536;

async function keyOf(provider) {
  const { data } = await svc.rpc("get_ai_key", { p_provider: provider });
  return data ?? null;
}

async function embed(text) {
  const gk = await keyOf("google");
  if (gk) {
    const res = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-embedding-001:embedContent?key=${gk}`,
      {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          model: "models/gemini-embedding-001",
          content: { parts: [{ text }] },
          outputDimensionality: DIMS,
        }),
      },
    );
    if (res.ok) {
      const d = await res.json();
      const v = d?.embedding?.values;
      if (v?.length === DIMS) return v;
      console.log(`  ! google คืน ${v?.length} มิติ (ต้องการ ${DIMS})`);
    } else console.log(`  ! google ${res.status}: ${(await res.text()).slice(0, 120)}`);
  }
  const ok = await keyOf("openai");
  if (ok) {
    const res = await fetch("https://api.openai.com/v1/embeddings", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${ok}` },
      body: JSON.stringify({ model: "text-embedding-3-small", input: text, dimensions: DIMS }),
    });
    if (res.ok) return (await res.json())?.data?.[0]?.embedding ?? null;
    console.log(`  ! openai ${res.status}: ${(await res.text()).slice(0, 120)}`);
  }
  return null;
}

// ---------- ลงข้อมูล ----------
let added = 0, updated = 0, embedded = 0, noEmbed = 0;

for (const row of SEED) {
  const { data: exist } = await svc.from("tax_knowledge").select("id").eq("topic", row.topic).maybeSingle();
  const payload = { ...row, updated_at: new Date().toISOString() };

  if (exist?.id) {
    await svc.from("tax_knowledge").update(payload).eq("id", exist.id);
    updated++;
  } else {
    await svc.from("tax_knowledge").insert(payload);
    added++;
  }
}
console.log(`\n== ความรู้ภาษี ==\n  เพิ่มใหม่ ${added} · อัปเดต ${updated}`);

// สร้าง embedding ให้แถวที่ยังไม่มี — แยกขั้นเพื่อให้เนื้อหาลงได้แม้คีย์ AI ยังไม่พร้อม
const { data: pending } = await svc.from("tax_knowledge").select("id,topic,content").is("embedding", null);
for (const r of pending ?? []) {
  const vec = await embed(`${r.topic}\n${r.content}`);
  if (!vec) { noEmbed++; continue; }
  await svc.from("tax_knowledge").update({ embedding: JSON.stringify(vec) }).eq("id", r.id);
  embedded++;
  console.log(`  embed  ${r.topic}`);
}

console.log(
  noEmbed === 0
    ? `  สร้างเวกเตอร์ ${embedded} แถว ครบแล้ว\n`
    : `  สร้างเวกเตอร์ ${embedded} แถว · ยังไม่มีเวกเตอร์ ${noEmbed} แถว (ค้นได้ด้วย trigram ไปก่อน)\n`,
);
