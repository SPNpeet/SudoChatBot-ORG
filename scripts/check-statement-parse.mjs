// ============================================================
//  ด่านตรวจ: แกะ statement ธนาคาร ต้องไม่เสนอ "เงินออก" เป็น "เงินเข้า"
//
//  ⚠️ ทำไมด่านนี้สำคัญกว่าที่เห็น (29 ส.ค. 2569)
//  หน้านำเข้า statement เป็นแบบ "อ่านมาเสนอ ผู้ใช้กดยืนยันรายแถว" ซึ่งปลอดภัยระดับหนึ่ง
//  แต่ถ้าระบบเสนอยอด *ถอนเงิน* มาเป็น *เงินเข้า* แล้วผู้ใช้กดผ่านเร็ว ๆ
//  จะได้รายได้ปลอมเข้าบัญชี ซึ่งดันยอดขายและภาษีขายให้เกินจริง
//  บั๊กนี้มีอยู่จริงในสูตรเดิม: statement ที่มีคอลัมน์ ถอน/ฝาก/คงเหลือ
//  แถวที่เป็นการถอนจะสกัดเลขได้ 2 ตัว (ถอน, คงเหลือ) แล้วสูตรเดิมหยิบตัวแรกมาเป็นเงินเข้า
// ============================================================
import { parseStatementText, explainNoRows } from "../src/lib/statement-parse.ts";

let bad = 0;
const ok = (cond, name, extra = "") => {
  if (cond) console.log(`  ถูก  ${name}`);
  else { bad++; console.log(`  ผิด  ${name}${extra ? ` — ${extra}` : ""}`); }
};

console.log("\n== แกะ statement ธนาคาร ==");

// 1. รูปแบบยอดฮิต: วันที่ · รายการ · ถอน · ฝาก · คงเหลือ
//    แถวถอนต้องไม่ถูกเสนอ แถวฝากต้องได้ยอดที่ถูกช่อง
{
  const text = [
    "รายการเดินบัญชี",
    "วันที่ รายการ ถอนเงิน ฝากเงิน ยอดคงเหลือ",
    "01/08/2569 โอนเงินเข้า พร้อมเพย์ 5,000.00 15,000.00",
    "02/08/2569 ถอนเงิน ATM 2,000.00 13,000.00",
    "03/08/2569 รับโอน ค่าบริการ 1,200.50 14,200.50",
  ].join("\n");
  const r = parseStatementText(text);
  ok(r.layout === "withdraw-deposit-balance", "จับหัวตาราง ถอน/ฝาก/คงเหลือ ได้", r.layout);
  const amts = r.rows.map((x) => x.amount);
  ok(!amts.includes(2000), "ยอดถอน 2,000 ไม่ถูกเสนอเป็นเงินเข้า", JSON.stringify(amts));
  ok(amts.includes(5000), "ยอดฝาก 5,000 ถูกเสนอ", JSON.stringify(amts));
  ok(amts.includes(1200.5), "ยอดรับโอน 1,200.50 ถูกเสนอ", JSON.stringify(amts));
  ok(!amts.includes(15000) && !amts.includes(13000), "ยอดคงเหลือไม่ถูกนับเป็นยอดธุรกรรม", JSON.stringify(amts));
}

// 1ก. เคสที่สูตรเดิมพลาดจริง (พิสูจน์แล้วด้วยการรันสูตรเดิม)
//     แถวถอนเงินที่ statement เขียนแค่ช่องทาง ไม่มีคำว่า "ถอน" ให้จับ
//     สูตรเดิมคืน 2,000 เป็นเงินเข้า — ต้องไม่เกิดขึ้นอีก
{
  const text = [
    "วันที่ รายการ ถอนเงิน ฝากเงิน ยอดคงเหลือ",
    "02/08/2569 ATM CDM SEACON 2,000.00 13,000.00",
  ].join("\n");
  const r = parseStatementText(text);
  ok(r.rows.length === 0,
    "แถวถอนที่ไม่มีคำว่าถอน ต้องไม่ถูกเสนอเป็นเงินเข้า (บั๊กเดิม)", JSON.stringify(r.rows));
}

// 2. แถวที่มีครบ 3 ช่อง (ถอน 0.00 / ฝาก x / คงเหลือ) ต้องหยิบช่องฝาก
{
  const text = [
    "วันที่ รายการ ถอน ฝาก คงเหลือ",
    "05/08/2569 เงินเข้า 0.00 3,300.00 20,000.00",
    "06/08/2569 ค่าธรรมเนียม 30.00 0.00 19,970.00",
  ].join("\n");
  const r = parseStatementText(text);
  const amts = r.rows.map((x) => x.amount);
  ok(amts.includes(3300), "หยิบช่องฝากถูกเมื่อมีครบ 3 ตัวเลข", JSON.stringify(amts));
  ok(!amts.includes(30), "ค่าธรรมเนียมไม่ถูกเสนอเป็นเงินเข้า", JSON.stringify(amts));
}

// 3. PDF ที่สกัดข้อความแล้ววันที่กับยอดตกคนละบรรทัด — เดิมหาไม่เจอเลยสักแถว
{
  const text = ["10/08/2569", "โอนเข้าจากลูกค้า", "7,500.00 22,000.00", "11/08/2569", "รับโอน", "500.00 22,500.00"].join("\n");
  const r = parseStatementText(text);
  ok(r.rows.length === 2, `ต่อบรรทัดที่ขาดกันได้ (เจอ ${r.rows.length} แถว)`, JSON.stringify(r.rows));
  ok(r.rows[0]?.amount === 7500, "ยอดของแถวที่ถูกต่อถูกต้อง", JSON.stringify(r.rows[0]));
}

// 4. รูปแบบคอลัมน์เดียว (ยอด + คงเหลือ) ที่ไม่มีหัวตารางถอน/ฝาก — ยังต้องอ่านได้เหมือนเดิม
{
  const text = ["12/08/2569 รับโอนเงิน 900.00 5,900.00"].join("\n");
  const r = parseStatementText(text);
  ok(r.rows.length === 1 && r.rows[0].amount === 900, "ไฟล์คอลัมน์เดียวยังอ่านได้", JSON.stringify(r.rows));
}

// 5. เลขที่บัญชี/เลขอ้างอิงต้องไม่ถูกจับเป็นยอดเงิน
{
  const text = ["13/08/2569 โอนเข้า ref 1234567890 บัญชี 037-7-12345-6 2,000.00 8,000.00"].join("\n");
  const r = parseStatementText(text);
  ok(r.rows.length === 1 && r.rows[0].amount === 2000,
    "เลขอ้างอิงที่ไม่มีทศนิยมไม่ถูกนับเป็นเงิน", JSON.stringify(r.rows));
}

// 6. ข้อความบอกเหตุผลตอนไม่เจอ ต้องบอกสิ่งที่วัดได้จริง ไม่ใช่ขอโทษลอย ๆ
{
  const noDate = parseStatementText("ใบสรุปยอดบัญชี\nยอดยกมา 1,000.00");
  ok(noDate.rows.length === 0, "ใบสรุปยอดไม่ถูกอ่านเป็นรายการ");
  ok(explainNoRows(noDate).includes("ไม่เจอบรรทัดที่มีวันที่"), "บอกได้ว่าไม่มีบรรทัดที่มีวันที่", explainNoRows(noDate));

  const allOut = parseStatementText("วันที่ รายการ ถอน ฝาก คงเหลือ\n01/08/2569 ถอนเงิน ATM 500.00 1,000.00");
  ok(allOut.rows.length === 0, "statement ที่มีแต่เงินออก ไม่เสนออะไรเลย");
  ok(explainNoRows(allOut).includes("เงินออก"), "บอกได้ว่าทุกแถวเป็นเงินออก", explainNoRows(allOut));
}

console.log(bad === 0 ? "\nสรุป: ผ่านทั้งหมด" : `\nสรุป: ผิด ${bad} ข้อ`);
process.exit(bad === 0 ? 0 : 1);
