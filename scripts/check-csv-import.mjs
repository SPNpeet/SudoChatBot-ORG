//  ตรวจตัวอ่านไฟล์ CSV ที่ลูกค้านำเข้า (เพิ่ม 6 ส.ค. 2569 — ไม่เคยตรวจเลย)
//
//  ⚠️ ทำไมต้องมี
//  ตัวแยกบรรทัด CSV เขียนเองทั้งหมดใน src/lib/excel.ts และเป็น "ประตู"
//  ที่ข้อมูลของลูกค้าไหลเข้าระบบบัญชี (นำเข้าสินค้า · นำเข้ารายการเดินบัญชี)
//  ถ้าแยกเซลล์ผิดแม้แถวเดียว ยอดเงินจะไปอยู่ผิดคอลัมน์แล้วลงบัญชีผิด
//  โดยที่ไม่มี error ให้เห็น — ไฟล์นำเข้าสำเร็จ ตัวเลขแค่ผิด
//
//  เคสที่พังง่ายและเจอจริงกับไฟล์จากฝั่งไทย:
//   · Excel ใส่ BOM มาเสมอ ไม่ตัด = หัวคอลัมน์แรกจับคู่ไม่ติด
//   · ชื่อบริษัทไทยมีคอมมาบ่อยมาก เช่น บริษัท ก จำกัด, สาขา 1
//   · Excel บน Windows จบบรรทัดด้วย CRLF
//   · เซลล์ว่างกลางแถว ถ้าหายไป = คอลัมน์เลื่อนทั้งแถว ยอดไปอยู่ช่องผิด
//   · ที่อยู่หลายบรรทัดในเซลล์เดียว
//
//  แยกเป็นไฟล์ของตัวเองเพราะต้องใช้ await ระดับบนสุดและ File API
//  ซึ่งชุดตรวจบัญชีหลักไม่ได้ใช้
// ============================================================
import { readSheet } from "../src/lib/excel.ts";

let failures = 0;
const ok = (cond, name, detail = "") => {
  if (!cond) { failures++; console.log(`  ผิด  ${name}${detail ? " — " + detail : ""}`); }
};
const csv = (t) => new File([t], "t.csv", { type: "text/csv" });
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);

console.log("\n== อ่านไฟล์ CSV ที่ลูกค้านำเข้า ==");

let r = await readSheet(csv("﻿ชื่อ,ราคา\nสินค้า ก,100"));
ok(eq(r[0], ["ชื่อ", "ราคา"]), "ตัด BOM ที่ Excel ใส่มา", JSON.stringify(r[0]));

r = await readSheet(csv('ชื่อ,ยอด\n"บริษัท ก จำกัด, สาขา 1",5350'));
ok(eq(r[1], ["บริษัท ก จำกัด, สาขา 1", "5350"]), "คอมมาในเซลล์ที่ครอบด้วยเครื่องหมายคำพูด", JSON.stringify(r[1]));

r = await readSheet(csv('ชื่อ\n"สินค้า ""พิเศษ"" รุ่นใหม่"'));
ok(eq(r[1], ['สินค้า "พิเศษ" รุ่นใหม่']), "เครื่องหมายคำพูดซ้อน", JSON.stringify(r[1]));

r = await readSheet(csv("ก,ข\r\n1,2\r\n"));
ok(r.length === 2 && eq(r[1], ["1", "2"]), "CRLF ของ Excel บน Windows", `${r.length} แถว`);

r = await readSheet(csv("ก,ข,ค\n1,,3"));
ok(eq(r[1], ["1", "", "3"]), "เซลล์ว่างกลางแถวต้องไม่ทำให้คอลัมน์เลื่อน", JSON.stringify(r[1]));

r = await readSheet(csv("ก,ข\n1,2\n"));
ok(r.length === 2, "บรรทัดว่างท้ายไฟล์ไม่นับเป็นแถว", `${r.length} แถว`);

r = await readSheet(csv('ที่อยู่\n"123 ถนนหนึ่ง\nแขวงสอง กทม."'));
ok(r.length === 2 && String(r[1][0]).includes("\n"), "ขึ้นบรรทัดใหม่ในเซลล์ (ที่อยู่หลายบรรทัด)", JSON.stringify(r));

r = await readSheet(csv("รายการ\nค่าน้ำค่าไฟ ก.ค. ๒๕๖๙"));
ok(r[1][0] === "ค่าน้ำค่าไฟ ก.ค. ๒๕๖๙", "ข้อความไทย + เลขไทยไม่เพี้ยน", String(r[1][0]));

console.log(failures === 0
  ? "  ถูก  ผ่านทุกเคส\n"
  : `\nสรุป: ไม่ผ่าน ${failures} ข้อ — ห้าม deploy จนกว่าจะแก้\n`);
process.exit(failures === 0 ? 0 : 1);
