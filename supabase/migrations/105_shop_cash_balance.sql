-- ============================================================
--  ยอดเงินสด + เงินฝาก "ตามสมุดบัญชี"
--
--  ⚠️ ชื่อที่ใช้บนหน้าจอสำคัญกว่าตัวเลข — อ่านให้จบก่อนแก้
--
--  แบบร่างหน้าจอที่เจ้าของอยากได้เขียนว่า "เงินสดคงเหลือ" เฉย ๆ ซึ่งใช้ไม่ได้
--  เพราะระบบนี้ **ไม่ได้ต่อกับบัญชีธนาคาร** จึงไม่มีทางรู้ยอดจริงในธนาคาร
--  ตัวเลขที่คำนวณได้คือ "ยอดตามสมุดบัญชี" ซึ่งต่างจากยอดธนาคารเสมอเมื่อมี
--  เช็คที่ยังไม่ขึ้นเงิน · ค่าธรรมเนียมที่ธนาคารหักแล้วแต่ยังไม่ได้ลงบัญชี ·
--  เงินโอนเข้าที่ยังไม่ได้บันทึก — การกระทบยอด (bank reconciliation) มีไว้แก้ตรงนี้
--
--  ถ้าเขียนว่า "เงินสดคงเหลือ" เฉย ๆ แล้วเจ้าของร้านเอาไปตัดสินใจจ่ายเงิน
--  โดยเชื่อว่านั่นคือยอดในธนาคาร = เงินไม่พอจริง เช็คเด้ง ซึ่งเป็นความเสียหายที่เรา
--  เป็นคนก่อด้วยการตั้งชื่อผิด ทิศที่ผิดแล้วอันตรายของระบบบัญชีคือ "ทำให้ดูดีเกินจริง"
--  (กติกาข้อ 7) — ยอดเงินที่ดูเยอะกว่าความจริงคือกรณีเดียวกันเป๊ะ
--
--  หน้าจอจึงต้องเขียนว่า "เงินสด + เงินฝาก" และกำกับว่า "ตามสมุดบัญชี"
--  ห้ามเปลี่ยนป้ายเป็น "เงินคงเหลือในบัญชี" หรืออะไรที่ทำให้เข้าใจว่าเป็นยอดธนาคาร
--
--  ⚠️ ทำไมเป็นฟังก์ชันฝั่งฐานข้อมูล ไม่ใช่ดึงแถวมาบวกฝั่ง Node
--  ยอดคงเหลือต้องรวม journal_lines **ตั้งแต่แถวแรกที่เคยลง** ไม่ใช่แค่ช่วงเดือนนี้
--  กิจการที่ใช้มานานจะมีหลักหมื่นแถว ดึงมาบวกฝั่งเว็บคือโหลดทั้งสมุดรายวัน
--  ลงหน้าแรกทุกครั้งที่เปิด
--
--  ⚠️ 1010/1020 มาจาก seed_chart_of_accounts (migration 051)
--  ถ้าวันหนึ่งเพิ่มผังบัญชีเงินสดรหัสใหม่ ต้องมาเติมที่นี่ด้วย ไม่งั้นยอดจะขาดไปเงียบ ๆ
-- ============================================================
create or replace function public.shop_cash_balance(p_shop_id uuid)
returns numeric
language plpgsql stable security definer set search_path to 'public' as $function$
declare
  v_total numeric;
begin
  -- security definer ข้าม RLS ได้ จึงต้องตรวจสิทธิ์เอง ไม่งั้นใครก็ถามยอดเงินของร้านอื่นได้
  if not public.is_shop_member(p_shop_id) then
    raise exception 'forbidden';
  end if;

  select coalesce(sum(l.debit - l.credit), 0)
    into v_total
  from public.journal_lines l
  join public.chart_of_accounts a on a.id = l.account_id
  where l.shop_id = p_shop_id
    and a.shop_id = p_shop_id
    and a.code in ('1010', '1020');

  return v_total;
end $function$;

comment on function public.shop_cash_balance(uuid) is
  'ยอดเงินสด(1010)+เงินฝาก(1020) ตามสมุดบัญชี — ไม่ใช่ยอดในธนาคารจริง ยังไม่ผ่านการกระทบยอด';

revoke all on function public.shop_cash_balance(uuid) from public, anon;
grant execute on function public.shop_cash_balance(uuid) to authenticated, service_role;
