-- ============================================================
--  096 — index ที่ขาดบนคีย์นอกของตารางบัญชีที่ใหญ่ที่สุด
--
--  พบจาก Supabase performance advisor (6 ส.ค. 2569 — ไม่เคยรันมาก่อนเลย)
--  journal_lines.account_id เป็น FK ที่ไม่มี index รองรับ
--
--  ทำไมเฉพาะตัวนี้ ทั้งที่ advisor แจ้ง 4 ตัว:
--   · journal_lines คือตารางที่โตเร็วที่สุดในระบบ (ทุกเอกสาร 1 ใบ = หลายบรรทัด)
--     และรายงานที่ลูกค้าเปิดบ่อยที่สุด (งบทดลอง แยกประเภท ภ.พ.30) join ด้วย account_id ทุกครั้ง
--   · อีก 3 ตัว (comment_replies, notice_dismissals, topups.plan_code) เป็นตารางเล็ก
--     หรือเป็นซากยุคแชทบอท — ใส่ index ไปก็เปลืองพื้นที่เขียนโดยไม่ได้อะไรกลับมา
--     index ที่ไม่มีใครใช้ไม่ได้ฟรี มันต้องถูกอัปเดตทุกครั้งที่เขียนแถว
--
--  ยังไม่กระทบอะไรตอนนี้เพราะข้อมูลยังน้อย — ใส่ตอนนี้เพราะตอนที่มันสำคัญจริง
--  คือตอนที่ลูกค้าเยอะแล้ว ซึ่งเป็นตอนที่ไม่มีใครอยากมานั่งแก้
-- ============================================================
create index if not exists journal_lines_account_idx on public.journal_lines using btree (account_id);
