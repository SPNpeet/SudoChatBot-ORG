-- ============================================================
--  097 — ให้เจ้าของกิจการลบข้อความในกล่องจดหมายได้เอง
--
--  ⚠️ ทำไม (8 ส.ค. 2569)
--  เดิม notifications มีแค่ policy select กับ update (ใช้ทำเครื่องหมาย "อ่านแล้ว")
--  ไม่มี policy delete = ข้อความสะสมอยู่ในฐานข้อมูลตลอดไป ลบไม่ได้เลยแม้แต่ของตัวเอง
--  ผู้ใช้กด "อ่านแล้ว" ได้อย่างเดียว แล้วมันหายไปจากสายตาโดยที่เอากลับมาดูก็ไม่ได้
--  และลบทิ้งจริง ๆ ก็ไม่ได้ — เจ้าของรายงานว่า "อ่านแล้วแต่ยังไม่ได้ลบ ไม่มีให้ลบอีก"
--
--  ให้ลบได้เฉพาะข้อความของกิจการที่ตัวเองเป็นสมาชิก (เงื่อนไขเดียวกับ select)
--  ข้อความพวกนี้เป็นการแจ้งเตือน ไม่ใช่หลักฐานทางบัญชี จึงลบได้โดยไม่กระทบสมุดรายวัน
-- ============================================================
drop policy if exists notifications_delete on public.notifications;
create policy notifications_delete on public.notifications
  for delete to authenticated using (public.is_shop_member(shop_id));

-- อ่านประวัติ "ที่อ่านแล้ว" ต้องเรียงตามเวลาเร็ว ๆ ได้ด้วย ไม่ใช่แค่ที่ยังไม่อ่าน
create index if not exists notifications_shop_created_idx
  on public.notifications (shop_id, created_at desc);
